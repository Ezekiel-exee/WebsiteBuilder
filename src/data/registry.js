import { lazy } from "react";

const sectionModules = import.meta.glob("../components/sections/*.jsx");
const sectionSourceModules = import.meta.glob("../components/sections/*.jsx", {
  query: "?raw",
  import: "default",
});

const sectionComponents = new Proxy(
  {},
  {
    get(_, exportName) {
      const path = `../components/sections/${String(exportName)}.jsx`;
      const loader = sectionModules[path];
      if (!loader) throw new Error(`Unknown component module: ${path}`);
      return lazy(loader);
    },
  },
);

const sectionSources = new Proxy(
  {},
  {
    get(_, exportName) {
      const path = `../components/sections/${String(exportName)}.jsx`;
      const loader = sectionSourceModules[path];
      if (!loader) throw new Error(`Unknown component source: ${path}`);
      return loader;
    },
  },
);

